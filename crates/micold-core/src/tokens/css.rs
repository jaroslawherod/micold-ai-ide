//! The design tokens as a CSS custom-property sheet (feature 028 — FR-030, SC-014).
//!
//! The published documentation site is dressed in the application's own design tokens rather than
//! in a copy of them. A copy would be a second source of truth that drifts the first time a colour
//! moves, and drift here is not cosmetic: every screenshot on the site is taken from the running
//! application, so a site whose surfaces have gone stale frames a picture of the real ones.
//!
//! So this module is the one place the tokens become CSS, and it is a **pure function** — token set
//! in, stylesheet text out. It reads no environment, touches no file and makes no decision about
//! where the sheet is written; `src/bin/micold-tokens-css.rs` prints what it returns. That is what
//! lets the whole contract in `specs/028-docs-site-github-pages/contracts/theme-variables.md` be
//! asserted by unit tests in this file rather than by inspecting a build product.
//!
//! Two things are deliberately *not* emitted:
//!
//! - **`tracking`.** The type scale records Material's letter-spacing but the renderer never applies
//!   it (FR-042). Emitting it would let the site set a spacing no screenshot on the site can show.
//! - **Component anatomy and density.** Sizes for buttons, chips and list rows describe controls the
//!   documentation does not have (FR-029b). The site borrows the application's *look*, not its
//!   widgets.

use super::{ColorScheme, Rgb, Roles, elevation, motion, roles, shape, spacing, state, typography};
use std::fmt::Write as _;

/// The header every generated sheet opens with. Someone will open this file in an editor; the first
/// line is the only warning they get before they change something a build overwrites.
const HEADER: &str =
    "/* GENERATED by micold-tokens-css from crates/micold-core/src/tokens/. Do not edit. */";

/// The complete stylesheet: the header comment, the light block, and the dark block.
///
/// Every name is emitted in both blocks. Scheme-independent tokens — the type scale, corner radii,
/// durations, state opacities — are therefore repeated with identical values rather than hoisted
/// into the light block and inherited. That is deliberate: a reader (and the test) can then check
/// one property, "both blocks define the same names", instead of reasoning about which subset the
/// dark block is entitled to omit. A missing name does not fail loudly in CSS; it falls back to an
/// initial value and the page quietly renders in something that is not the application's palette.
pub fn stylesheet() -> String {
    let mut out = String::with_capacity(8 * 1024);
    out.push_str(HEADER);
    out.push('\n');
    block(&mut out, ":root", ColorScheme::Light, "light scheme");
    block(
        &mut out,
        ":root[data-scheme=\"dark\"]",
        ColorScheme::Dark,
        "dark scheme — same names, dark values",
    );
    out
}

fn block(out: &mut String, selector: &str, scheme: ColorScheme, comment: &str) {
    let r = roles(scheme);
    let _ = writeln!(out, "{selector} {{ /* {comment} */");
    for (name, value) in color_roles(&r) {
        declare(out, &format!("--micold-{}", kebab(name)), &hex(value));
    }
    type_scale(out);
    corner_radii(out);
    elevations(out, &r, scheme);
    motion(out);
    states(out);
    spacing_scale(out);
    out.push_str("}\n");
}

fn declare(out: &mut String, name: &str, value: &str) {
    let _ = writeln!(out, "  {name}: {value};");
}

/// The identifier *is* the contract: renaming a token in this crate renames the variable, `site.css`
/// stops finding it, and the site build fails. That coupling is the point — the alternative is a
/// site that silently keeps painting last release's colours.
fn kebab(identifier: &str) -> String {
    identifier.replace('_', "-")
}

fn hex(color: Rgb) -> String {
    format!("#{:02x}{:02x}{:02x}", color.r, color.g, color.b)
}

/// Every field of [`Roles`], paired with its own identifier.
///
/// Spelled out rather than derived: a macro over the struct would emit whatever fields happen to
/// exist, so adding a private helper field would silently add a public CSS variable. This list is
