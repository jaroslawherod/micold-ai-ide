/// Size, line height and weight — but never `tracking`, which the renderer records and does not
/// apply (FR-042). A site that applied it would set its prose at a spacing no screenshot on that
/// same page can show.
fn type_scale(out: &mut String) {
    for role in typography::ALL {
        let base = format!("--micold-type-{}", kebab(role.name));
        declare(out, &format!("{base}-size"), &format!("{}px", role.size));
        declare(
            out,
            &format!("{base}-line-height"),
            &format!("{}px", role.line_height),
        );
        declare(out, &format!("{base}-weight"), &role.weight.to_string());
    }
}

fn corner_radii(out: &mut String) {
    for (name, value) in [
        ("none", shape::NONE),
        ("extra-small", shape::EXTRA_SMALL),
        ("small", shape::SMALL),
        ("medium", shape::MEDIUM),
        ("large", shape::LARGE),
        ("extra-large", shape::EXTRA_LARGE),
        ("full", shape::FULL),
    ] {
        declare(
            out,
            &format!("--micold-shape-corner-{name}"),
            &format!("{value}px"),
        );
    }
}

/// Each level emits **both** of its cues: the complete `box-shadow`, and the tonal surface it
/// resolves to. Carrying only the shadow would lose the level entirely in the dark scheme, where
/// the tone is the primary cue and a black shadow is nearly invisible (`elevation.rs` module docs).
fn elevations(out: &mut String, r: &Roles, scheme: ColorScheme) {
    for level in elevation::LEVELS {
        let shadow = match level.shadow {
            None => "none".to_string(),
            Some(s) => {
                let alpha = match scheme {
                    ColorScheme::Light => s.alpha_light,
                    ColorScheme::Dark => s.alpha_dark,
                };
                format!(
                    "0 {}px {}px rgba({}, {}, {}, {alpha})",
                    s.offset_y, s.blur, r.shadow.r, r.shadow.g, r.shadow.b
                )
            }
        };
        declare(out, &format!("--micold-elevation-{}", level.level), &shadow);
        declare(
            out,
            &format!("--micold-elevation-{}-surface", level.level),
            &hex(r.elevation_surface(level.level)),
        );
    }
    declare(
        out,
        "--micold-scrim-opacity",
        &elevation::SCRIM_ALPHA.to_string(),
    );
}

fn motion(out: &mut String) {
    for (name, value) in [
        ("short-1", motion::duration::SHORT_1),
        ("short-2", motion::duration::SHORT_2),
        ("short-3", motion::duration::SHORT_3),
        ("short-4", motion::duration::SHORT_4),
        ("medium-1", motion::duration::MEDIUM_1),
        ("medium-2", motion::duration::MEDIUM_2),
        ("medium-3", motion::duration::MEDIUM_3),
        ("medium-4", motion::duration::MEDIUM_4),
        ("long-1", motion::duration::LONG_1),
        ("long-2", motion::duration::LONG_2),
        ("long-3", motion::duration::LONG_3),
        ("long-4", motion::duration::LONG_4),
    ] {
        declare(
            out,
            &format!("--micold-motion-duration-{name}"),
            &format!("{value}ms"),
        );
    }
    for (name, e) in [
        ("standard", motion::STANDARD),
        ("standard-accelerate", motion::STANDARD_ACCELERATE),
        ("standard-decelerate", motion::STANDARD_DECELERATE),
        ("emphasized", motion::EMPHASIZED),
        ("emphasized-accelerate", motion::EMPHASIZED_ACCELERATE),
        ("emphasized-decelerate", motion::EMPHASIZED_DECELERATE),
    ] {
        declare(
            out,
            &format!("--micold-motion-easing-{name}"),
            &format!("cubic-bezier({}, {}, {}, {})", e.x1, e.y1, e.x2, e.y2),
        );
    }
}

fn states(out: &mut String) {
    for (name, value) in [
        ("hover", state::HOVER),
        ("focus", state::FOCUS),
        ("pressed", state::PRESSED),
        ("dragged", state::DRAGGED),
        ("selected", state::SELECTED),
        ("disabled-content", state::DISABLED_CONTENT),
        ("disabled-container", state::DISABLED_CONTAINER),
    ] {
        declare(
            out,
            &format!("--micold-state-{name}-opacity"),
            &value.to_string(),
        );
    }
    declare(
        out,
        "--micold-state-focus-ring-width",
        &format!("{}px", state::FOCUS_RING_WIDTH),
    );
}

fn spacing_scale(out: &mut String) {
    for (name, value) in [
        ("xs", spacing::XS),
        ("sm", spacing::SM),
        ("md", spacing::MD),
        ("lg", spacing::LG),
        ("xl", spacing::XL),
    ] {
        declare(out, &format!("--micold-spacing-{name}"), &format!("{value}px"));
    }
}

#[cfg(test)]
