//! The design tokens as a TypeScript module for the web client (issue #1950, FR-034).
//!
//! Same role as `css.rs`, for the Expo client rather than the documentation site: the client builds
//! its Material 3 theme from this one generated module instead of a hand-copied palette. A pure
//! function, token set in, module text out: no environment, file or clock input, so the bytes are
//! the same on every run (SC-002). `src/bin/micold-tokens-ts.rs` writes what it returns, and
//! `specs/1950-micold-tokens-ts/contracts/tokens-module.md` is the contract the tests below assert.
//!
//! Not emitted, as in `css.rs`: `tracking` (recorded, never applied, FR-042), component anatomy,
//! density, and fonts. Numbers are unitless (dp, ms, opacity 0-1) and easings are
//! `[x1, y1, x2, y2]` tuples, which React Native's `Easing.bezier` takes directly.

use super::elevation::{self, SurfaceRole};
use super::{roles, state, tables, typography, ColorScheme, Rgb};

/// The first line of every generated module. Someone will open the file in an editor; this is the
/// only warning they get before changing something a build overwrites.
const HEADER: &str =
    "// GENERATED by micold-tokens-ts from crates/micold-core/src/tokens/. Do not edit.";

/// The complete module text.
pub fn module() -> String {
    let mut out = String::with_capacity(12 * 1024);
    out.push_str(HEADER);
    out.push('\n');
    export(&mut out, "colors", &colors());
    export(&mut out, "typeScale", &type_scale());
    export(&mut out, "shape", &named(tables::CORNER_RADII, 1));
    export(&mut out, "elevation", &elevations());
    export(&mut out, "motion", &motion());
    export(&mut out, "state", &states());
    export(&mut out, "spacing", &named(tables::SPACING, 1));
    out
}

/// One `export const name = <body> as const;`, after a blank line.
fn export(out: &mut String, name: &str, body: &str) {
    out.push('\n');
    out.push_str(&format!("export const {name} = {body} as const;\n"));
}

fn colors() -> String {
    let scheme = |s| {
        let entries: Vec<_> = tables::color_roles(&roles(s))
            .into_iter()
            .map(|(name, rgb)| (camel(name), format!("\"{}\"", hex(rgb))))
            .collect();
        object(1, &entries)
    };
    object(
        0,
        &[
            ("light".into(), scheme(ColorScheme::Light)),
            ("dark".into(), scheme(ColorScheme::Dark)),
        ],
    )
}

fn hex(c: Rgb) -> String {
    format!("#{:02x}{:02x}{:02x}", c.r, c.g, c.b)
}

/// Size, line height and weight; never `tracking`, which the renderer records and does not apply.
fn type_scale() -> String {
    let entries: Vec<_> = typography::ALL
        .iter()
        .map(|role| {
            let fields = [
                ("size".to_string(), role.size.to_string()),
                ("lineHeight".to_string(), role.line_height.to_string()),
                ("weight".to_string(), role.weight.to_string()),
            ];
            (camel(role.name), object(1, &fields))
        })
        .collect();
    object(0, &entries)
}

/// A flat `name: number` family at `depth`, keys camel-cased.
fn named<V: std::fmt::Display>(
    table: impl IntoIterator<Item = (&'static str, V)>,
    depth: usize,
) -> String {
    let entries: Vec<_> = table
        .into_iter()
        .map(|(name, v)| (camel(name), v.to_string()))
        .collect();
    object(depth - 1, &entries)
}

fn surface_key(role: SurfaceRole) -> &'static str {
    match role {
        SurfaceRole::Surface => "surface",
        SurfaceRole::SurfaceContainerLow => "surfaceContainerLow",
        SurfaceRole::SurfaceContainer => "surfaceContainer",
        SurfaceRole::SurfaceContainerHigh => "surfaceContainerHigh",
        SurfaceRole::SurfaceContainerHighest => "surfaceContainerHighest",
    }
}

/// Levels mirror `elevation::Level`; the tinted surface is a colour-role key, not a colour, so the
/// family is scheme-independent and only the shadow alpha is split as `{ light, dark }`.
fn elevations() -> String {
    let level = |l: &elevation::Level| {
        let shadow = match l.shadow {
            None => "null".to_string(),
            Some(s) => object(
                3,
                &[
                    ("offsetY".into(), s.offset_y.to_string()),
                    ("blur".into(), s.blur.to_string()),
                    (
                        "alpha".into(),
                        object(
                            4,
                            &[
                                ("light".into(), s.alpha_light.to_string()),
                                ("dark".into(), s.alpha_dark.to_string()),
                            ],
                        ),
                    ),
                ],
            ),
        };
        object(
            2,
            &[
                ("level".into(), l.level.to_string()),
                ("surface".into(), format!("\"{}\"", surface_key(l.surface))),
                ("shadow".into(), shadow),
            ],
        )
    };
    let levels: Vec<String> = elevation::LEVELS.iter().map(level).collect();
    object(
        0,
        &[
            ("levels".into(), array(1, &levels)),
            ("scrimAlpha".into(), elevation::SCRIM_ALPHA.to_string()),
        ],
    )
}

fn motion() -> String {
    let easings: Vec<_> = tables::EASINGS
        .iter()
        .map(|(name, e)| {
            (
                camel(name),
                format!("[{}, {}, {}, {}]", e.x1, e.y1, e.x2, e.y2),
            )
        })
        .collect();
    object(
        0,
        &[
            ("duration".into(), named(tables::DURATIONS, 2)),
            ("easing".into(), object(1, &easings)),
        ],
    )
}

fn states() -> String {
    object(
        0,
        &[
            ("opacity".into(), named(tables::STATES, 2)),
            ("focusRingWidth".into(), state::FOCUS_RING_WIDTH.to_string()),
        ],
    )
}

/// `lowerCamelCase` of a Rust identifier or CSS-style name: `on_surface` -> `onSurface`,
/// `extra-small` -> `extraSmall`, `short-1` -> `short1`.
fn camel(name: &str) -> String {
    let mut out = String::new();
    for (i, part) in name.split(['_', '-']).enumerate() {
        let mut chars = part.chars();
        match chars.next() {
            Some(c) if i > 0 => {
                out.push(c.to_ascii_uppercase());
                out.push_str(chars.as_str());
            }
            Some(c) => {
                out.push(c);
                out.push_str(chars.as_str());
            }
            None => {}
        }
    }
    out
}

/// A TypeScript object literal from already-rendered `(key, value)` pairs, one per line, whose
/// closing brace sits at `depth` levels of two-space indent; an empty family is `{}` rather than a
/// block with nothing in it.
fn object(depth: usize, entries: &[(String, String)]) -> String {
    block(
        "{",
        "}",
        depth,
        entries.iter().map(|(k, v)| format!("{k}: {v}")),
    )
}

/// An array literal from already-rendered elements, laid out as [`object`] is.
fn array(depth: usize, items: &[String]) -> String {
    block("[", "]", depth, items.iter().cloned())
}

fn block(open: &str, close: &str, depth: usize, lines: impl Iterator<Item = String>) -> String {
    let inner = "  ".repeat(depth + 1);
    let mut out = String::new();
    for line in lines {
        out.push_str(&format!("{inner}{line},\n"));
    }
    if out.is_empty() {
        return format!("{open}{close}");
    }
    format!("{open}\n{out}{}{close}", "  ".repeat(depth))
}

#[cfg(test)]
mod tests {
    use super::*;

    /// The lines strictly inside the first block opened by `opener` (a full line, e.g. `  light: {`),
    /// up to the closing line at the same indent.
    fn block<'a>(lines: &[&'a str], opener: &str) -> Vec<&'a str> {
        let indent = opener.len() - opener.trim_start().len();
        let mut lines = lines.iter().copied();
        assert!(
            lines.any(|l| l == opener),
            "no line `{opener}` in the module"
        );
        let mut out = Vec::new();
        for line in lines {
            let closes = line.len() > indent
                && line[..indent].trim().is_empty()
                && line[indent..].starts_with('}')
                || line.starts_with(&format!("{}]", " ".repeat(indent)));
            if closes {
                return out;
            }
            out.push(line);
        }
        panic!("`{opener}` is never closed");
    }

    /// `key: value,` at exactly `indent` spaces -> (key, value), skipping deeper lines.
    fn entries<'a>(lines: &[&'a str], indent: usize) -> Vec<(&'a str, &'a str)> {
        let pad = " ".repeat(indent);
        lines
            .iter()
            .filter(|l| l.starts_with(&pad) && !l[indent..].starts_with(' '))
            .filter_map(|l| l[indent..].split_once(": "))
            .map(|(k, v)| (k, v.trim_end_matches(',')))
            .collect()
    }

    fn value<'a>(lines: &[&'a str], indent: usize, key: &str) -> &'a str {
        entries(lines, indent)
            .into_iter()
            .find(|(k, _)| *k == key)
            .unwrap_or_else(|| panic!("no key `{key}` at indent {indent}"))
            .1
    }

    fn camel(name: &str) -> String {
        super::camel(name)
    }

    /// The `#rrggbb` of `--micold-<role>` in the stylesheet's light (`:root {`) or dark block.
    fn css_colour(scheme: ColorScheme, role: &str) -> String {
        let sheet = crate::tokens::css::stylesheet();
        let opener = match scheme {
            ColorScheme::Light => ":root {",
            ColorScheme::Dark => ":root[data-scheme=\"dark\"] {",
        };
        let from = sheet.find(opener).expect("block") + opener.len();
        let to = from + sheet[from..].find('}').expect("closed");
        let needle = format!("  --micold-{}: ", role.replace('_', "-"));
        sheet[from..to]
            .lines()
            .find_map(|l| l.strip_prefix(&needle))
            .unwrap_or_else(|| panic!("css has no {role}"))
            .trim_end_matches(';')
            .to_string()
    }

    fn number(n: impl std::fmt::Display) -> String {
        n.to_string()
    }

    #[test]
    fn module_is_deterministic() {
        assert_eq!(module(), module());
        assert!(!module().is_empty());
    }

    #[test]
    fn every_colour_role_in_both_schemes_equals_the_stylesheet() {
        let text = module();
        let text: Vec<&str> = text.lines().collect();
        for (key, scheme) in [("light", ColorScheme::Light), ("dark", ColorScheme::Dark)] {
            let lines = block(&text, &format!("  {key}: {{"));
            for (role, _) in tables::color_roles(&roles(scheme)) {
                let got = value(&lines, 4, &camel(role));
                assert_eq!(
                    got,
                    format!("\"{}\"", css_colour(scheme, role)),
                    "{key}.{role}"
                );
            }
        }
    }

    #[test]
    fn light_and_dark_have_the_same_keys() {
        let text = module();
        let text: Vec<&str> = text.lines().collect();
        let keys = |s: &str| -> Vec<String> {
            entries(&block(&text, &format!("  {s}: {{")), 4)
                .into_iter()
                .map(|(k, _)| k.to_string())
                .collect()
        };
        let (light, dark) = (keys("light"), keys("dark"));
        assert_eq!(light.len(), 46);
        assert_eq!(light, dark);
    }

    #[test]
    fn every_key_is_a_plain_camel_case_identifier() {
        for line in module().lines().skip(1) {
            let Some((key, _)) = line.trim_start().split_once(':') else {
                continue;
            };
            if line.trim_start().starts_with("export") || key.starts_with(['}', ']', '{']) {
                continue;
            }
            let mut chars = key.chars();
            assert!(
                chars.next().is_some_and(|c| c.is_ascii_lowercase())
                    && chars.all(|c| c.is_ascii_alphanumeric()),
                "key `{key}` on line `{line}` is not ^[a-z][A-Za-z0-9]*$"
            );
        }
    }

    #[test]
    fn numbers_have_no_exponent_and_no_trailing_zero_fraction() {
        for line in module().lines() {
            let Some((_, v)) = line.split_once(": ") else {
                continue;
            };
            let v = v.trim_end_matches(',').trim_matches(['[', ']']);
            for token in v.split(", ") {
                if token.starts_with(|c: char| c.is_ascii_digit() || c == '-') {
                    assert!(!token.contains(['e', 'E']), "exponent in `{line}`");
                    assert!(!token.ends_with(".0"), "trailing .0 in `{line}`");
                }
            }
        }
    }

    #[test]
    fn type_scale_shape_motion_state_and_spacing_equal_their_tables() {
        let text = module();
        let text: Vec<&str> = text.lines().collect();
        let scale = block(&text, "export const typeScale = {");
        for role in typography::ALL {
            let lines = block(&scale, &format!("  {}: {{", camel(role.name)));
            assert_eq!(value(&lines, 4, "size"), number(role.size));
            assert_eq!(value(&lines, 4, "lineHeight"), number(role.line_height));
            assert_eq!(value(&lines, 4, "weight"), number(role.weight));
            assert!(
                !lines.iter().any(|l| l.contains("tracking")),
                "tracking is not emitted"
            );
        }
        let shape = block(&text, "export const shape = {");
        for (name, v) in tables::CORNER_RADII {
            assert_eq!(value(&shape, 2, &camel(name)), number(v), "shape {name}");
        }
        let motion = block(&text, "export const motion = {");
        let durations = block(&motion, "  duration: {");
        for (name, v) in tables::DURATIONS {
            assert_eq!(value(&durations, 4, &camel(name)), number(v), "{name}");
        }
        let easings = block(&motion, "  easing: {");
        for (name, e) in tables::EASINGS {
            let expected = format!("[{}, {}, {}, {}]", e.x1, e.y1, e.x2, e.y2);
            assert_eq!(value(&easings, 4, &camel(name)), expected, "{name}");
        }
        let st = block(&text, "export const state = {");
        let opacity = block(&st, "  opacity: {");
        for (name, v) in tables::STATES {
            assert_eq!(value(&opacity, 4, &camel(name)), number(v), "{name}");
        }
        assert_eq!(
            value(&st, 2, "focusRingWidth"),
            number(state::FOCUS_RING_WIDTH)
        );
        let spacing = block(&text, "export const spacing = {");
        for (name, v) in tables::SPACING {
            assert_eq!(value(&spacing, 2, &camel(name)), number(v), "{name}");
        }
    }

    #[test]
    fn elevation_levels_mirror_the_desktop_levels() {
        let text = module();
        let text: Vec<&str> = text.lines().collect();
        let el = block(&text, "export const elevation = {");
        let levels = block(&el, "  levels: [");
        // Each level is a `    {` ... `    },` object; split on the opener lines.
        let mut objects: Vec<Vec<&str>> = Vec::new();
        for line in &levels {
            if *line == "    {" {
                objects.push(Vec::new());
            } else if *line != "    }," {
                objects.last_mut().expect("inside a level").push(line);
            }
        }
        assert_eq!(objects.len(), elevation::LEVELS.len());
        for (obj, level) in objects.iter().zip(elevation::LEVELS) {
            assert_eq!(value(obj, 6, "level"), number(level.level));
            let surface = match level.surface {
                SurfaceRole::Surface => "surface",
                SurfaceRole::SurfaceContainerLow => "surfaceContainerLow",
                SurfaceRole::SurfaceContainer => "surfaceContainer",
                SurfaceRole::SurfaceContainerHigh => "surfaceContainerHigh",
                SurfaceRole::SurfaceContainerHighest => "surfaceContainerHighest",
            };
            assert_eq!(value(obj, 6, "surface"), format!("\"{surface}\""));
            match level.shadow {
                None => assert_eq!(value(obj, 6, "shadow"), "null"),
                Some(s) => {
                    assert_eq!(value(obj, 6, "shadow"), "{");
                    assert_eq!(value(obj, 8, "offsetY"), number(s.offset_y));
                    assert_eq!(value(obj, 8, "blur"), number(s.blur));
                    assert_eq!(value(obj, 10, "light"), number(s.alpha_light));
                    assert_eq!(value(obj, 10, "dark"), number(s.alpha_dark));
                }
            }
        }
        assert_eq!(value(&el, 2, "scrimAlpha"), number(elevation::SCRIM_ALPHA));
    }

    #[test]
    fn an_empty_family_renders_as_an_empty_object() {
        assert_eq!(object(0, &[]), "{}");
    }

    #[test]
    fn the_first_line_is_the_contract_header() {
        assert_eq!(
            module().lines().next(),
            Some(
                "// GENERATED by micold-tokens-ts from crates/micold-core/src/tokens/. Do not edit."
            )
        );
    }
}
