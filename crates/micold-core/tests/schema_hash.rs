#[test]
fn the_build_fingerprint_is_a_separate_mechanism_from_the_schema_hash() {
    use micold_core::protocol::version::BUILD_FINGERPRINT;

    // Both are generated by `build.rs`, and it would be easy to assume one subsumes the other. It
    // does not: `SCHEMA_HASH` covers three protocol files and answers "do we agree about the
    // wire?", while the fingerprint covers this crate's whole source tree and answers "were we
    // built from the same thing?". A change to `settings.rs` moves the second and not the first,
    // and that gap is exactly what a stale `:dev` image falls into.
    assert!(!BUILD_FINGERPRINT.is_empty());
    assert!(BUILD_FINGERPRINT.chars().all(|c| c.is_ascii_hexdigit()));

    let hash_hex: String = SCHEMA_HASH.iter().map(|b| format!("{b:02x}")).collect();
    assert!(
        !hash_hex.starts_with(BUILD_FINGERPRINT),
        "the fingerprint must not be a prefix of the schema hash — that would mean one is \
         derived from the other and the gap above is not covered"
    );
}

