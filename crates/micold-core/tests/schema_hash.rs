/// The protocol version feature 026 bumped to.
///
/// Pinned, not read from a constant, because that is what makes this a gate rather than a mirror.
/// Feature 026 makes **five** wire changes — `provider` on `ClientMsg::SessionCreate` and on
/// `SessionSummary`, and `default_ai_cli` on `DaemonSettings`, `SettingsSet` and `SettingsChanged`
/// — and the whole point of doing them in one edit is that the hash moves **once**. A second bump
/// later in the feature, when US3 comes to consume the outbound field, fails here.
///
/// It read 6 while this branch was based on a `main` at 5. Rebasing onto a `main` that had since
/// bumped 5 → 6 for `SessionSummary::live_shells` (feature 012, BUG-003) moved this feature's one
/// bump up to 7 — which is exactly the "another feature's bump" case the assertion below names,
/// and the constant follows it rather than the feature bumping twice.
///
/// It moved again, 7 → 8, when feature 027 merged: 027 had developed against 6 and 7 of its own
/// while 026 was taking those same numbers here, so the merged wire carries both features'
/// changes and both cannot be 7. Same case, same answer — the constant follows the bump, and 026
/// still costs exactly one.
///
/// And 8 → 9 for `010` BUG-022, which makes a client *window* nameable on the wire
/// (`ClientMsg::Hello::client_instance`, and a `ClientIdentity` on `DaemonMsg::Displaced::by` and
/// `RefusalReason::ProjectBusy::holder`). Third time, same case, same answer.
///
/// And 9 → 10 for feature 029's `ClientMsg::WorktreeRefresh`. Fourth time, same case, same answer:
/// the constant follows the wire, and 026 still costs exactly one bump. That this line has now been
/// written four times is the gate working — each of those features had to come here and say which
/// bump was theirs.
///
/// And 10 → 11 for feature 029's Pi provider (`AiCli::Pi`, and `pi_activity_component` on
/// `DaemonSettings` and `SettingsSet`), which had developed against the 10 `WorktreeRefresh` took.
/// Fifth time, same case, same answer.
///
/// And 11 → 12 for `002` BUG-003's `ClientMsg::ProjectActivate`. Sixth time, same case, same answer.
///
/// And 12 → 13 for `006` BUG-007's `ClientMsg::TerminalColorScheme`. Seventh time, same case, same
/// answer.
///
/// And 13 → 14 for feature 032's `SessionLabel::Derived`, which `SessionSummary.title` carries.
/// Eighth time, same case, same answer — with one difference worth writing down: `SessionLabel`
/// lives in `session.rs`, which `SCHEMA_HASH` does **not** cover (it hashes the protocol sources
/// only), so the hash did not move and nothing but this pin forced the bump (032 research R3).
///
/// And 14 → 15 for `029` BUG-001's `cwd` on `ClientMsg::AiCliAvailabilityRequest`, which had
/// developed against the 13 that feature 032's label took to 14. Ninth time, same case, same
/// answer.
///
/// And 15 → 16 for feature 034's `ClientMsg::RemoteList` / `OperationResult::RemoteList`, which
/// let the client ask for a project's own remote URLs. Tenth time, same case, same answer.
///
/// And 16 → 17 for feature 034's `tool_server_enabled` on `DaemonSettings` and `SettingsSet`
/// (FR-004). Eleventh time, same case, same answer.
///
/// And 17 → 18 for feature 034's confirmations (`DaemonMsg::ConfirmationRequested` /
/// `ConfirmationWithdrawn`, `ClientMsg::ConfirmationAnswer`, FR-014). Twelfth time, same case, same
/// answer.
///
/// And 18 → 19 for feature 034's `cross_session_access` on `DaemonSettings` and `SettingsSet`
/// (FR-016). Thirteenth time, same case, same answer.
///
/// And 19 → 20 for feature 037's `env` on `DaemonMsg::AiCliAvailability`: the state of the
/// environment the answer was walked in, which had developed against the 17 that feature 034
/// took to 18 and then 19. Fourteenth time, same case, same answer.
///
/// And 20 → 21 for feature 039's `ClientMsg::WindowView` and `SessionSummary::attention_seq`: a
/// window reports the session it has in view, and every session carries its count of attention
/// events. Fifteenth time, same case, same answer.
///
/// And 21 → 22 for feature 040's `ClientMsg::MergedBranchCheck` /
/// `OperationResult::MergedBranchCheck` and `pr_status_enabled` on `DaemonSettings` and
/// `SettingsSet`: one bump for both, taking 22 as
/// feature 039 took 21. Sixteenth time, same case, same answer.
///
/// And 22 → 23 for feature 039's `ClientMsg::AttentionClaim` and `DaemonMsg::AttentionGranted`: a
/// window claims an attention event and the service grants each one once. Seventeenth time, same
/// case, same answer.
///
/// And 23 → 24 for feature 039's `SessionSummary::unread`: every session carries whether it is
/// unread. Eighteenth time, same case, same answer.
///
/// And 24 → 25 for feature 039's `ClientMsg::SessionReveal` and `DaemonMsg::RevealSession`: a
/// click on a notification is sent to the service, which forwards it to one window. Nineteenth
/// time, same case, same answer.
///
/// And 25 → 26 for feature 039's `activation` on both reveal messages: the Wayland activation
/// token of the click rides with the reveal. Twentieth time, same case, same answer.
/// And 26 → 27 for feature 039's `desktop_notifications` on `DaemonSettings` and `SettingsSet`
/// (contract W4): the service holds the Desktop notifications switch for every window. Twenty-first
/// time, same case, same answer.
///
/// And 27 → 28 for feature 582's attach messages (`AttachDiscover`, `AttachApply`, `AttachReport`,
/// `OperationResult::AttachApplied`): new variants an older peer cannot decode.
///
/// And 28 → 29 for feature 010 BUG-592's `DaemonMsg::ShellOpenFailed`: a refused shell open is
/// reported to the client that asked. A new variant an older client cannot decode.
///
/// And 29 → 30 for feature 011 BUG-442's `ClientMsg::SessionRestart`: the AI CLI's manual restart
/// re-sources the session's directory first. A new variant an older service cannot decode.
///
/// And 30 → 31 for feature 613's `kind` on `DaemonMsg::AttentionGranted` (wire W5.1): the grant
/// says which kind of event the window notifies for. An older peer would fail to decode it.
///
/// And 31 → 32 for feature 613's `DaemonMsg::SessionErrorNotice` (wire W5.2): the service tells
/// one window that a session ended because of an error. A new variant an older client cannot
/// decode.
///
/// And 32 → 33 for feature 613's `notification_kinds` and `long_task_threshold_secs` on
/// `DaemonSettings` and `SettingsSet` (wire W5.3, W5.4, W5.6): the service holds the per-kind
/// switches and the long-task threshold for every window. An older peer cannot decode them.
const FEATURE_026_PROTOCOL_VERSION: u32 = 33;

#[test]
fn the_wire_changes_for_this_feature_cost_exactly_one_version_bump() {
    assert_eq!(
        PROTOCOL_VERSION, FEATURE_026_PROTOCOL_VERSION,
        "the protocol version moved. If that is another feature's bump, update this constant \
         along with the rest of that feature's wire change. If it is feature 026 bumping a second \
         time, it should not be: US3 consumes `SessionSummary::provider`, which T029 already put \
         on the wire, and consuming a field is not a wire change"
    );
}

#[test]
fn every_field_this_feature_added_is_present_in_one_protocol_source() {
    // The other half of "one bump": the bump has to *cover* all five. A version that moved while
    // one of the additions was still to come would satisfy the test above and still cost a second
    // move later.
    //
    // Read from the source text rather than from the types, deliberately — this file's whole
    // subject is the text `build.rs` hashes, and a field added to a *different* file would not
    // change the hash however correct the type looked.
    let (messages, _grid, _envelope) = read_protocol_source();
    for anchor in [
        // Inbound: the client's resolved choice.
        "SessionCreate {",
        // Outbound: the label a row reads (FR-016).
        "pub provider: AiCli,",
        // The service-owned preference, in all three of its shapes.
        "pub default_ai_cli: AiCli,",
        "default_ai_cli: Option<AiCli>,",
    ] {
        assert!(
            messages.contains(anchor),
            "`{anchor}` is not in messages.rs — feature 026's wire change is incomplete, so the \
             single bump this feature is allowed does not yet cover all of it"
        );
    }
    assert_eq!(
        canonicalize(&messages).matches("provider: AiCli,").count(),
        2,
        "exactly two `provider: AiCli` fields ride the wire: one inbound on `SessionCreate`, one \
         outbound on `SessionSummary`"
    );
}

