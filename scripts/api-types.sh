#!/usr/bin/env bash
# Regenerates the client API's checked-in artifacts from the Rust wire types (#1732, FR-009, FR-010):
#
#   packages/protocol/schema/client-api.schema.json    micold-api-schema (crates/micold-core)
#   packages/protocol/src/generated/client-api.ts      json-schema-to-typescript over that schema
#   packages/protocol/tests/vectors/sidebar-order.json the FR-012 vectors (client_api_vectors.rs)
#
# Usage:
#   scripts/api-types.sh            regenerate all three
#   scripts/api-types.sh --check    fail when the schema or the TypeScript is stale, naming the file
#                                   and this command; changes nothing
#   scripts/api-types.sh --check --ts-only
#                                   check only that the TypeScript matches the checked-in schema (no
#                                   cargo; CI's web client job). The schema itself is then checked by
#                                   crates/micold-core/tests/client_api_schema.rs, the vectors by
#                                   client_api_vectors.rs.
#
# API_TYPES_SCHEMA and API_TYPES_TS override the two checked paths (scripts/tests/api-types.test.sh).
# Needs `pnpm install` for json2ts. See docs/development/api-types.md.

set -euo pipefail
cd "$(dirname "$0")/.."

schema="${API_TYPES_SCHEMA:-packages/protocol/schema/client-api.schema.json}"
ts="${API_TYPES_TS:-packages/protocol/src/generated/client-api.ts}"
json2ts=packages/protocol/node_modules/.bin/json2ts
regen="scripts/api-types.sh"

check=0 ts_only=0
for arg in "$@"; do
	case "$arg" in
	--check) check=1 ;;
	--ts-only) ts_only=1 ;;
	*) echo "usage: scripts/api-types.sh [--check [--ts-only]]" >&2; exit 2 ;;
	esac
done

if [ ! -x "$json2ts" ]; then
	echo "api-types: $json2ts is missing; run pnpm install" >&2
	exit 2
fi

# to_ts <schema> <out>: the TypeScript module for <schema>, formatted the same way every time.
to_ts() {
	"$json2ts" --input "$1" --output "$2" --unreachableDefinitions --additionalProperties=false \
		--bannerComment "/* Generated by scripts/api-types.sh from packages/protocol/schema/client-api.schema.json (#1732). Do not edit: change the Rust types in crates/micold-core/src/client_api/messages.rs and rerun the script. */"
}

if [ "$check" = 0 ]; then
	mkdir -p "$(dirname "$schema")" "$(dirname "$ts")"
	scripts/build-lock.sh cargo run -q -p micold-core --bin micold-api-schema -- "$schema"
	to_ts "$schema" "$ts"
	MICOLD_WRITE_VECTORS=1 scripts/build-lock.sh cargo test -q -p micold-core --test main \
		client_api_vectors::the_checked_in_vectors_equal_the_generated_ones >/dev/null
	echo "api-types: wrote $schema, $ts and the FR-012 vectors"
	exit 0
fi

tmp="$(mktemp -d)"
trap 'rm -rf "$tmp"' EXIT

# same <fresh> <committed>: fails, naming the file and the command, when they differ.
same() {
	if [ ! -f "$2" ]; then
		echo "DRIFT: $2 is missing. Regenerate it: $regen"
		return 1
	fi
	if ! cmp -s "$1" "$2"; then
		echo "DRIFT: $2 is stale. Regenerate it: $regen"
		return 1
	fi
}

rc=0
if [ "$ts_only" = 0 ]; then
	scripts/build-lock.sh cargo run -q -p micold-core --bin micold-api-schema -- "$tmp/schema.json"
	same "$tmp/schema.json" "$schema" || rc=1
fi
if [ -f "$schema" ]; then
	to_ts "$schema" "$tmp/client-api.ts"
	same "$tmp/client-api.ts" "$ts" || rc=1
fi
[ "$rc" = 0 ] && echo "ok    $schema and $ts are current"
exit "$rc"
